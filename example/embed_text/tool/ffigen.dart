import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final packageRoot = Platform.script.resolve('../');
  final header = packageRoot.resolve('src/embed_text.h');
  await FfiGenerator(
    output: Output(
      dart: DartOutput(
        path: packageRoot.resolve('lib/src/third_party/embed_text.g.dart'),
      ),
      recordUseMapping: packageRoot.resolve(
        'lib/src/third_party/embed_text.record_use_mapping.g.dart',
      ),
      preamble: '// Generated by package:ffigen. Do not edit manually.',
    ),
    input: Input(entryPoints: [header], include: (uri) => uri == header),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = {
            'embed_text_data',
            'embed_text_size',
          }.contains(node.originalName);
          node.isLeaf = true;
          node.recordUse = true;
        },
      ),
    ],
  ).generate();
}
